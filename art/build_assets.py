#!/usr/bin/env python3
"""FPGA assets of the Desk view from art/bg.png + art/layout.json (see make_svg.py):
  rtl/desk_tiles.hex   8x8 tiles, one 32-bit word per tile row (8 pixels x 4 bits, left pixel in the MSBs)
  rtl/desk_map.hex     100x75 tile numbers (10 bits), row by row
  rtl/desk_assets.svh  palette, TV picture origin, key_at() hit test of the keypad, RST and FN
  art/bg_quant.png     the quantized background, for review
  art/desk_expect.png  bg_quant + art/sample_frame.txt in the TV: what the Verilator test must draw
Palette entries 14 (dot) and 15 (led) are drawn by the HDL only."""
from PIL import Image
import json, os

ROOT = os.path.dirname(os.path.abspath(__file__)) + '/..'
lay = json.load(open(f'{ROOT}/art/layout.json'))
N = lay['names']
pal = [tuple(int(c[i:i + 2], 16) for i in (1, 3, 5)) for c in lay['palette']]
W, H, T = 800, 600, 8
MW, MH = W // T, H // T

img = Image.open(f'{ROOT}/art/bg.png').convert('RGB')
px = img.load()
cache = {}
idx = [[0] * W for _ in range(H)]
for y in range(H):
    for x in range(W):
        c = px[x, y]
        if c not in cache:
            cache[c] = min(range(14), key=lambda i: sum((a - b) ** 2 for a, b in zip(c, pal[i])))
        idx[y][x] = cache[c]
lx, ly = lay['led']                                     # tape LED: dynamic colour 15
for y in range(ly - 5, ly + 6):
    for x in range(lx - 5, lx + 6):
        if (x - lx) ** 2 + (y - ly) ** 2 <= 22: idx[y][x] = N.index('led')

tiles, tmap = {}, []
for ty in range(MH):
    for tx in range(MW):
        t = tuple(tuple(idx[ty * T + y][tx * T:tx * T + T]) for y in range(T))
        if t not in tiles: tiles[t] = len(tiles)
        tmap.append(tiles[t])
assert len(tiles) <= 1024, len(tiles)
with open(f'{ROOT}/rtl/desk_tiles.hex', 'w') as f:
    for t in tiles:
        for row in t:
            f.write('%08x\n' % sum(v << (4 * (7 - i)) for i, v in enumerate(row)))
with open(f'{ROOT}/rtl/desk_map.hex', 'w') as f:
    f.write('\n'.join('%03x' % v for v in tmap) + '\n')

PX, PY, DOT = lay['picture']
with open(f'{ROOT}/rtl/desk_assets.svh', 'w') as f:
    f.write('// generated by art/build_assets.py from art/layout.json: do not edit\n')
    f.write(f'localparam int DESK_TILES = {len(tiles)};\n')
    f.write(f'localparam int PIC_X = {PX}, PIC_Y = {PY}, PIC_DOT = {DOT};\n')
    f.write('localparam logic [23:0] DESK_PAL [0:15] = \'{\n    '
            + ', '.join("24'h" + c[1:] for c in lay['palette']) + '\n};\n')
    for n in N: f.write(f'localparam logic [3:0] C_{n.upper()} = 4\'d{N.index(n)};\n')
    f.write('// key under (x, y): 0-15 hex keys, 16 RST, 17 FN, 31 none\n'
            'function automatic logic [4:0] key_at(input logic [9:0] x, input logic [9:0] y);\n'
            '    key_at = 5\'d31;\n')
    for k, (x0, y0, x1, y1) in lay['keys'].items():
        code = {'RST': 16, 'FN': 17}.get(k, None)
        code = int(k) if code is None else code
        f.write(f"    if (x >= 10'd{x0} && x <= 10'd{x1} && y >= 10'd{y0} && y <= 10'd{y1}) key_at = 5'd{code};\n")
    f.write('endfunction\n')

q = Image.new('RGB', (W, H))
q.putdata([pal[v] for row in idx for v in row])
q.save(f'{ROOT}/art/bg_quant.png')
frame = [l.rstrip('\n') for l in open(f'{ROOT}/art/sample_frame.txt')][:32]
qp = q.load()
for y in range(32 * DOT):
    for x in range(64 * DOT):
        if frame[y // DOT][x // DOT] == '#': qp[PX + x, PY + y] = pal[N.index('dot')]
q.save(f'{ROOT}/art/desk_expect.png')
print(f'{len(tiles)} tiles, {len(cache)} source colours')
